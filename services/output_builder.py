from datetime import datetime
from math import ceil
def buildOutput(npc) -> str:
    created_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    safe_name = npc.name.strip().replace(" ", "_")

    if not safe_name:
        safe_name = "NPC"

    armor_str = npc.armor if isinstance(npc.armor, str) else -1
    inv_lines = "\n    ".join(
        f'CreateInvItems (self, {item["item"]}, {item["quantity"]});'
        for item in npc.inv_items
    )
    return f"""// Generated by NPC Creator Studio — {created_at}
    instance MOD_{npc.id}_{safe_name} (Npc_Default)
    {{
        //========================================
        // PRIMARY DATA
        //========================================
        name = "{npc.name}";
        npctype ={"NPCTYPE_FRIEND" if npc.friend else npc.type};
        guild = { npc.guild or "GIL_NONE"};
        level = {npc.level};
        voice = {npc.voice};
        id = {npc.id};
        flags = {"NPC_FLAG_IMMORTAL" if npc.immortal else 0};
        //========================================
        // ATTRIBUTES
        //========================================
        B_SetAttributesToChapter(self,{int(ceil(npc.level/17))});
        //attribute[ATR_STRENGTH] = {npc.str};
        //attribute[ATR_DEXTERITY] = {npc.dex};
        //attribute[ATR_MANA_MAX] = {npc.mana};
        //attribute[ATR_MANA] = {npc.mana};
        //attribute[ATR_HITPOINTS_MAX] = {npc.hp};
        //attribute[ATR_HITPOINTS] = {npc.hp};
        //========================================
        // VISUALS
        //========================================
        Mdl_SetVisual (self, "HUMANS.MDS");
        Mdl_ApplyOverlayMds  (self, "{npc.walking if npc.walking else "HUMANS_MILITIA.MDS"}");
        Mdl_SetNpcVisual    (self, "hum_body_Naked0", {npc.body_tex}, {npc.skin_color}, "{npc.head if npc.head else "HUM_HEAD_PONY"}", {npc.face}, {npc.teeth_tex}, {armor_str});
        B_Scale (self);
        Mdl_SetModelFatness (self, {npc.fatness});
        fight_tactic = {npc.fight if npc.fight else "FAI_Human_Strong"};
        daily_routine = Rtn_{npc.id}_{safe_name}_01;
        //========================================
        // TALENTS
        //========================================
        B_SetFightSkills 	(self, {npc.level}); 
        //Npc_SetTalentSkill (self, NPC_TALENT_1H, {npc.t1h});
        //Npc_SetTalentSkill (self, NPC_TALENT_2H, {npc.t2h});
        //Npc_SetTalentSkill (self, NPC_TALENT_BOW, {npc.bow});
        //Npc_SetTalentSkill (self, NPC_TALENT_CROSSBOW, {npc.cbow});
        //Npc_SetTalentSkill	(self, NPC_TALENT_MAGE,			{npc.magic});
        //========================================
        // INVENTORY
        //========================================
        {inv_lines}
    }};
        //========================================
        // ROUTINES
        //========================================
    FUNC VOID Rtn_{npc.id}_{safe_name}_01 ()
    {{	
        TA_Position	(00,00,12,00,"WP_INTRO_FALL3");
        TA_Position	(12,00,00,00,"WP_INTRO_FALL3");
    }};

"""